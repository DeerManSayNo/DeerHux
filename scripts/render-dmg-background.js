// Native Finder artwork: derive visual values from the same tokens as the app.
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const { ArrowRight } = require("lucide-react");
const layout = require("./dmg-layout.json");

const root = path.resolve(__dirname, "..");
const globals = fs.readFileSync(path.join(root, "app/globals.css"), "utf8");
const dark = globals.match(/html\.dark\s*\{([^}]+)\}/)?.[1];
if (!dark) throw new Error("Missing dark theme tokens");
const source = fs.readFileSync(path.join(root, "app/design-tokens.css"), "utf8") + dark;
const tokens = Object.fromEntries([...source.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const lightSource = globals.match(/:root\s*\{([^}]+)\}/)?.[1];
if (!lightSource) throw new Error("Missing light theme tokens");
const lightTokens = Object.fromEntries([...lightSource.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
function lightToken(name) {
  if (!lightTokens[name]) throw new Error(`Missing light design token: ${name}`);
  return lightTokens[name];
}
function token(name) {
  if (!tokens[name]) throw new Error(`Missing design token: ${name}`);
  return tokens[name];
}
function size(name) { return parseFloat(token(name)); }

const { width, height } = layout;
const arrow = renderToStaticMarkup(React.createElement(ArrowRight, {
  x: width / 2 - 16, y: layout.app.y - 16, width: 32, height: 32,
  color: lightToken("accent"), strokeWidth: 1.75,
}));
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
  <!-- Generated by scripts/render-dmg-background.js; edit the generator, not this file. -->
  <rect width="${width}" height="${height}" fill="${token("bg")}"/>
  <g font-family="PingFang SC, -apple-system, sans-serif" text-anchor="middle">
    <text x="${width / 2}" y="48" font-size="${size("text-base")}" font-weight="${token("weight-semibold")}" fill="${token("brand")}">DeerHux</text>
    <text x="${width / 2}" y="108" font-size="${size("text-xl") * 2}" font-weight="${token("weight-semibold")}" fill="${token("text")}">让想法，开始运行。</text>
    <text x="${width / 2}" y="144" font-size="${size("text-lg")}" fill="${token("text-muted")}">你的桌面 Agent 工作台</text>
    <text x="${width / 2}" y="196" font-size="${size("text-base")}" fill="${token("text-muted")}">将 DeerHux 拖入 Applications，即可安装</text>
    <rect x="32" y="224" width="${width - 64}" height="196" rx="${size("radius-window")}" fill="${lightToken("bg-panel")}" stroke="${lightToken("border")}"/>
    ${arrow}
    <text x="${width / 2}" y="348" font-size="${size("text-sm")}" fill="${lightToken("text-muted")}">拖动安装</text>
    <text x="${width / 2}" y="456" font-size="${size("text-xs")}" fill="${token("text-dim")}">安装完成后，请从“应用程序”打开 DeerHux</text>
  </g>
</svg>\n`;

async function main() {
  const target = path.join(root, "assets/dmg-background");
  fs.writeFileSync(`${target}.svg`, svg);
  await sharp(Buffer.from(svg)).png().toFile(`${target}.png`);
  // TIFF representations preserve logical dimensions on Retina Finder windows.
  // Keep intermediate images outside the source tree.
  const os = require("os");
  const { execFileSync } = require("child_process");
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "deerhux-dmg-art-"));
  try {
    for (const scale of [1, 2]) {
      await sharp(Buffer.from(svg), { density: 72 * scale })
        .withMetadata({ density: 72 * scale }).tiff({ compression: "lzw" })
        .toFile(path.join(temporary, `${scale}x.tiff`));
    }
    execFileSync("tiffutil", ["-cathidpicheck", path.join(temporary, "1x.tiff"), path.join(temporary, "2x.tiff"), "-out", `${target}.tiff`]);
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
  console.log(`Rendered DMG artwork: ${width} × ${height} pt, 1× / 2×`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
